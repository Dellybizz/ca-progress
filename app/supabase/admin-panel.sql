create extension if not exists pgcrypto;

create table if not exists public.subscription_plans (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  name text not null,
  rank integer unique not null check (rank >= 0),
  price_monthly numeric(10,2) not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.subscription_plans (slug,name,rank,price_monthly)
values ('free','Free',0,0),('pro','Pro',10,0),('premium','Premium',20,0)
on conflict (slug) do nothing;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','moderator')),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table if not exists public.user_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_id uuid not null references public.subscription_plans(id),
  status text not null default 'active' check (status in ('active','trialing','paused','cancelled','expired')),
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.app_sections (
  id uuid primary key default gen_random_uuid(),
  section_key text unique not null,
  label text not null,
  description text not null default '',
  route text not null,
  enabled boolean not null default true,
  audience text not null default 'all' check (audience in ('all','guest','member')),
  minimum_plan_rank integer not null default 0,
  sort_order integer not null default 100,
  starts_at timestamptz,
  ends_at timestamptz,
  appearance jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);


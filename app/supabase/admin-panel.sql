create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id),
  action text not null,
  target_type text not null,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin(required_roles text[] default array['owner','admin','moderator'])
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_users where user_id=auth.uid() and role=any(required_roles)); $$;

alter table public.subscription_plans enable row level security;
alter table public.admin_users enable row level security;
alter table public.user_subscriptions enable row level security;
alter table public.app_sections enable row level security;
alter table public.admin_audit_logs enable row level security;

create policy "plans readable" on public.subscription_plans for select using (true);
create policy "plans managed by owners and admins" on public.subscription_plans for all using (public.is_admin(array['owner','admin'])) with check (public.is_admin(array['owner','admin']));
create policy "admins read own or admin list" on public.admin_users for select using (user_id=auth.uid() or public.is_admin(array['owner','admin']));
create policy "owners manage admins" on public.admin_users for all using (public.is_admin(array['owner'])) with check (public.is_admin(array['owner']));
create policy "subscriptions read own" on public.user_subscriptions for select using (user_id=auth.uid() or public.is_admin(array['owner','admin']));
create policy "subscriptions managed by admins" on public.user_subscriptions for all using (public.is_admin(array['owner','admin'])) with check (public.is_admin(array['owner','admin']));
create policy "sections readable" on public.app_sections for select using (true);
create policy "sections managed by admins" on public.app_sections for all using (public.is_admin(array['owner','admin'])) with check (public.is_admin(array['owner','admin']));
create policy "audit readable by owners" on public.admin_audit_logs for select using (public.is_admin(array['owner']));
create policy "admins write audit" on public.admin_audit_logs for insert with check (public.is_admin());

-- Allows appointed moderators/admins to remove community messages.
create policy "moderators delete community messages"
on public.community_messages for delete
using (public.is_admin(array['owner','admin','moderator']));


export function getSubjectsForSelection(
  level: CourseLevel,
  group: CourseGroup
): SubjectName[] {
  if (level === "Foundation") {
    return Object.keys(
      foundationSyllabus
    ) as SubjectName[];
  }

  if (group === "Both") {
    return Object.keys(
      courseSyllabi[level]
    ) as SubjectName[];
  }

  return subjectsByGroup[level][group];
}
